# ---------------- MARKS AND FEEDBACK ----------------

def save_marks(submission_id, marks_obtained, max_marks, feedback):
    connection = get_connection()

    try:
        connection.execute(
            """
            INSERT INTO marks (
                submission_id, marks_obtained, max_marks,
                feedback, evaluated_at
            )
            VALUES (%s, %s, %s, %s, %s)
            ON CONFLICT (submission_id) DO UPDATE SET
                marks_obtained = EXCLUDED.marks_obtained,
                max_marks = EXCLUDED.max_marks,
                feedback = EXCLUDED.feedback,
                evaluated_at = EXCLUDED.evaluated_at
            """,
            (
                submission_id,
                marks_obtained,
                max_marks,
                feedback,
                datetime.now()
            )
        )

        row = connection.execute(
            """
            SELECT s.id AS student_id, u.id AS user_id, a.title
            FROM submissions sub
            JOIN students s ON s.id = sub.student_id
            JOIN users u ON u.student_id = s.id
            JOIN assignments a ON a.id = sub.assignment_id
            WHERE sub.id = %s
            """,
            (submission_id,)
        ).fetchone()

        if row:
            connection.execute(
                """
                INSERT INTO notifications (user_id, title, message)
                VALUES (%s, %s, %s)
                """,
                (
                    row["user_id"],
                    "Assignment evaluated",
                    f"Your assignment '{row['title']}' has been evaluated."
                )
            )

        connection.commit()
        return True

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()


