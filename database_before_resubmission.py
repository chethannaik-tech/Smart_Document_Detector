# ---------------- SIMILARITY REPORTS ----------------

def save_similarity_results(assignment_id, results):
    connection = get_connection()

    try:
        invalidate_similarity_report(connection, assignment_id)

        assignment = connection.execute(
            """
            SELECT semester
            FROM assignments
            WHERE id = %s
            """,
            (assignment_id,)
        ).fetchone()

        if not assignment:
            raise ValueError("Assignment not found")

        for item in results:
            valid = connection.execute(
                """
                SELECT COUNT(*) AS total
                FROM students
                WHERE id IN (%s, %s)
                  AND semester = %s
                """,
                (
                    item["student1_id"],
                    item["student2_id"],
                    assignment["semester"]
                )
            ).fetchone()["total"]

            if valid != 2:
                continue

            connection.execute(
                """
                INSERT INTO similarity_results (
                    assignment_id,
                    student1_id,
                    student2_id,
                    similarity_percent
                )
                VALUES (%s, %s, %s, %s)
                """,
                (
                    assignment_id,
                    item["student1_id"],
                    item["student2_id"],
                    item.get(
                        "similarity_percent",
                        item.get("similarity", 0)
                    )
                )
            )

        connection.execute(
            """
            INSERT INTO similarity_report_runs
            (assignment_id, generated_at)
            VALUES (%s, %s)
            """,
            (assignment_id, datetime.now())
        )

        connection.commit()

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()


def get_similarity_results(assignment_id):
    connection = get_connection()

    try:
        rows = connection.execute(
            """
            SELECT
                sr.student1_id,
                s1.name AS student1_name,
                s1.register_number AS student1_register,
                s1.semester AS semester1,
                sr.student2_id,
                s2.name AS student2_name,
                s2.register_number AS student2_register,
                s2.semester AS semester2,
                sr.similarity_percent
            FROM similarity_results sr
            JOIN assignments a ON a.id = sr.assignment_id
            JOIN students s1 ON s1.id = sr.student1_id
            JOIN students s2 ON s2.id = sr.student2_id
            WHERE sr.assignment_id = %s
              AND s1.semester = a.semester
              AND s2.semester = a.semester
            ORDER BY sr.similarity_percent DESC
            """,
            (assignment_id,)
        ).fetchall()

        return [dict(row) for row in rows]

    finally:
        connection.close()


