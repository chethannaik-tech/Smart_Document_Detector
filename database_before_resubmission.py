import psycopg
from psycopg.rows import dict_row
from dotenv import load_dotenv
from werkzeug.security import generate_password_hash, check_password_hash


# ---------------- CONFIGURATION ----------------

BASE_DIR = os.path.dirname(os.path.abspath(__file__))

load_dotenv(os.path.join(BASE_DIR, ".env"))

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError(
        "DATABASE_URL is missing. Check your .env file."
    )


# ---------------- DATABASE CONNECTION ----------------

def get_connection():
    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row
    )


# ---------------- DATABASE INITIALIZATION ----------------

def init_db():
    connection = get_connection()

    try:
        statements = [

            """
            CREATE TABLE IF NOT EXISTS students (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                register_number TEXT UNIQUE NOT NULL,
                department TEXT,
                email TEXT,
                semester INTEGER
            )
            """,

            """
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL,
                student_id BIGINT
            )
            """,

            """
            CREATE TABLE IF NOT EXISTS assignments (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title TEXT NOT NULL,
                description TEXT,
                start_date TEXT,
                end_date TEXT,
                max_pages INTEGER DEFAULT 30,
                similarity_threshold DOUBLE PRECISION DEFAULT 40,
                semester INTEGER,
                subject TEXT,
                department TEXT,
                reference_file TEXT,
                max_marks DOUBLE PRECISION DEFAULT 100,
                accepted_format TEXT DEFAULT 'pdf',
                created_by BIGINT,
                created_at TIMESTAMP
            )
            """,

            """
            CREATE TABLE IF NOT EXISTS submissions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                student_id BIGINT REFERENCES students(id),
                assignment_id BIGINT REFERENCES assignments(id),
                file_name TEXT NOT NULL,
                original_name TEXT,
                submitted_at TEXT,
                resubmission_allowed BOOLEAN DEFAULT FALSE
            )
            """,

            """
            CREATE TABLE IF NOT EXISTS similarity_report_runs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                assignment_id BIGINT UNIQUE,
                generated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
            """,

            """
            CREATE TABLE IF NOT EXISTS similarity_results (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                assignment_id BIGINT NOT NULL,
                student1_id BIGINT NOT NULL,
                student2_id BIGINT NOT NULL,
                similarity_percent DOUBLE PRECISION NOT NULL,
                generated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
            """,

            """
            CREATE TABLE IF NOT EXISTS teachers (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT UNIQUE REFERENCES users(id),
                name TEXT NOT NULL,
                email TEXT,
                department TEXT
            )
            """,

            """
            CREATE TABLE IF NOT EXISTS subjects (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                subject_name TEXT NOT NULL,
                subject_code TEXT UNIQUE,
                department TEXT,
                semester INTEGER
            )
            """,

            """
            CREATE TABLE IF NOT EXISTS marks (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                submission_id BIGINT UNIQUE NOT NULL REFERENCES submissions(id),
                marks_obtained DOUBLE PRECISION NOT NULL,
                max_marks DOUBLE PRECISION NOT NULL,
                feedback TEXT,
                evaluated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
            """,

            """
            CREATE TABLE IF NOT EXISTS notifications (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id),
                title TEXT NOT NULL,
                message TEXT NOT NULL,
                is_read BOOLEAN DEFAULT FALSE,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
            """
        ]

        for statement in statements:
            connection.execute(statement)

        # Safe migrations for existing tables

        migrations = [
            ("assignments", "max_pages", "INTEGER DEFAULT 30"),
            ("assignments", "similarity_threshold", "DOUBLE PRECISION DEFAULT 40"),
            ("assignments", "semester", "INTEGER"),
            ("assignments", "subject", "TEXT"),
            ("assignments", "department", "TEXT"),
            ("assignments", "reference_file", "TEXT"),
            ("assignments", "max_marks", "DOUBLE PRECISION DEFAULT 100"),
            ("assignments", "accepted_format", "TEXT DEFAULT 'pdf'"),
            ("assignments", "created_by", "BIGINT"),
            ("assignments", "created_at", "TIMESTAMP"),
            ("students", "email", "TEXT"),
            ("students", "semester", "INTEGER"),
            ("submissions", "original_name", "TEXT"),
            ("submissions", "submitted_at", "TEXT"),
            ("submissions", "resubmission_allowed", "BOOLEAN DEFAULT FALSE"),
            ("users", "student_id", "BIGINT"),
        ]

        for table, column, definition in migrations:
            connection.execute(
                f"""
                ALTER TABLE {table}
                ADD COLUMN IF NOT EXISTS {column} {definition}
                """
            )

        connection.commit()
        print("PostgreSQL database initialized successfully.")

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()


# ---------------- STUDENTS AND USERS ----------------

def create_student_account(
    name, register_number, email, department, semester, password
):
    connection = get_connection()

    try:
        student = connection.execute(
            """
            INSERT INTO students
            (name, register_number, email, department, semester)
            VALUES (%s, %s, %s, %s, %s)
            RETURNING id
            """,
            (name, register_number, email, department, semester)
        ).fetchone()

        student_id = student["id"]

        connection.execute(
            """
            INSERT INTO users
            (username, password_hash, role, student_id)
            VALUES (%s, %s, 'student', %s)
            """,
            (
                register_number,
                generate_password_hash(password),
                student_id
            )
        )

        connection.commit()
        return True

    except psycopg.IntegrityError:
        connection.rollback()
        return False

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()


